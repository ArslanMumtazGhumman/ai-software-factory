/**
 * Every document is rendered from one validated plan, so the documents cannot
 * disagree with each other or with the backlog.
 */
export const DOCUMENT_NAMES = [
  'PRODUCT.md',
  'REQUIREMENTS.md',
  'ARCHITECTURE.md',
  'UX_PLAN.md',
  'DATA_MODEL.md',
  'TEST_PLAN.md',
  'RELEASE_PLAN.md',
  'RESEARCH.md',
  'TASKS.json',
] as const;
export type DocumentName = (typeof DOCUMENT_NAMES)[number];

const LABEL: Record<Statement['basis'], string> = {
  'user-provided': 'User-provided',
  verified: 'Verified',
  assumption: 'Assumption (unverified)',
  recommendation: 'Recommendation (AI-generated)',
};

const bullets = (items: readonly string[], empty = '_None._') => (items.length === 0 ? empty : items.map((i) => `- ${i}`).join('\n'));
const header = (title: string, plan: ProductPlan) =>
  `# ${title}: ${plan.product.name}\n\n> Generated by the AI Software Factory planner from the approved idea. Statements are labelled as user-provided, verified (with a source), assumption or recommendation.\n`;

function statementLines(statements: readonly Statement[], basis: Statement['basis']): string {
  const list = statements.filter((s) => s.basis === basis);
  return bullets(list.map((s) => `${s.statement}${s.sourceIds.length ? ` (${s.sourceIds.join(', ')})` : ''}`));
}

function sourceLine(s: SourceRef): string {
  const parts = [`**${s.id}** ${s.title}`, `kind: ${s.kind}`];
  if (s.url) parts.push(s.url);
  parts.push(s.retrievedAt ? `retrieved ${s.retrievedAt}` : 'retrieval date: not recorded');
  return `- ${parts.join(' - ')}${s.notes ? `\n  ${s.notes}` : ''}`;
}

export function taskBody(t: PlanTask, docsDir = 'docs'): string {
  return [
    t.scope,
    '',
    'Deliverables:',
    bullets(t.deliverables),
    '',
    `Checks (factory validation commands): ${t.checks.join(', ')}`,
    `Risk: ${t.risk}${t.riskFlags.length ? ` (${t.riskFlags.join(', ')})` : ''}`,
    'Completion evidence:',
    bullets(t.evidence),
    '',
    `Covers: ${t.covers.join(', ') || 'foundation'}${t.entities.length ? ` | Entities: ${t.entities.join(', ')}` : ''}${t.screens.length ? ` | Screens: ${t.screens.join(', ')}` : ''}`,
    `Specification: ${['PRODUCT', 'REQUIREMENTS', 'ARCHITECTURE', 'DATA_MODEL', 'UX_PLAN', 'TEST_PLAN'].map((d) => `${docsDir}/${d}.md`).join(', ')}.`,
  ].join('\n');
}

/** The backlog in the existing task engine's schema (validated by its own parser). */
export function backlogTasks(plan: ProductPlan, docsDir = 'docs'): Task[] {
  return parseTaskList(
    plan.tasks.map((t) => ({
      id: t.id,
      title: t.title,
      description: taskBody(t, docsDir),
      dependencies: t.dependencies,
      acceptanceCriteria: t.acceptanceCriteria,
      status: 'pending',
      retryCount: 0,
      results: [],
    })),
  );
}

export function tasksDocument(plan: ProductPlan, docsDir = 'docs'): TasksDocument {
  return { schemaVersion: TASKS_SCHEMA_VERSION, tasks: backlogTasks(plan, docsDir) };
}

export function projectSpec(plan: ProductPlan, slug: string, idea: IdeaInput, docsDir: string): ProjectSpec {
  return {
    id: slug,
    name: plan.product.name,
    description: `${plan.product.problem}\n\nValue: ${plan.product.valueProposition}\n\nThe full specification is in ${docsDir}/ (PRODUCT.md, REQUIREMENTS.md, ARCHITECTURE.md, UX_PLAN.md, DATA_MODEL.md, TEST_PLAN.md, RELEASE_PLAN.md).`,
    goals: plan.product.mvpScope,
    constraints: [
      ...(idea.constraints ? [idea.constraints] : []),
      `Stack: ${plan.architecture.stack.map((s) => `${s.layer}: ${s.choice}`).join('; ')}`,
      ...plan.requirements.nonFunctional.filter((r) => r.mvp).map((r) => `${r.id} (${r.category}): ${r.requirement}`),
      'Never commit secrets; configuration values come from environment variables listed in RELEASE_PLAN.md.',
      'Do not deploy, publish or create paid resources.',
    ].slice(0, 40),
  };
}

/** Slug used as project id and directory name. */
export function slugify(name: string): string {
  const s = name
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48)
    .replace(/-+$/g, '');
  return /^[a-z0-9]/.test(s) ? s : `project-${s || 'new'}`.slice(0, 48);
}

/**
 * The generated project's factory config. Limits, agent permissions and budgets
 * come from the workspace only; the planner contributes commands, which the
 * plan validator restricted to allowlisted, narrow forms. Validated with the
 * factory's own config parser.
 */
export function factoryConfigFor(plan: ProductPlan, workspace: WorkspaceConfig, layout: { projectRoot: string; dataDir: string; configDir: string }) {
  const d = workspace.projectDefaults;
  const executables = [...new Set(plan.commands.map((c) => c.executable))];
  const lowRisk = plan.tasks.filter((t) => t.risk === 'low' && !t.riskFlags.some((f) => SENSITIVE_FLAGS.includes(f))).map((t) => t.id);
  const raw = {
    version: 1,
    projectRoot: layout.projectRoot,
    dataDir: layout.dataDir,
    limits: { maxRetries: d.maxRetries, maxTasksPerRun: d.maxTasksPerRun, commandTimeoutMs: d.commandTimeoutMs, agentTimeoutMs: d.agentTimeoutMs },
    allowedExecutables: executables,
    commands: Object.fromEntries(plan.commands.map((c) => [c.name, { executable: c.executable, args: c.args, ...(c.description ? { description: c.description } : {}) }])),
    agent: {
      type: 'claude-code',
      executable: 'claude',
      permissionMode: 'dontAsk',
      tools: ['Read', 'Edit', 'Write', 'Glob', 'Grep'],
      allowedTools: ['Read', 'Edit', 'Write', 'Glob', 'Grep'],
      passEnv: d.agent.passEnv,
      ...(d.agent.model !== undefined ? { model: d.agent.model } : {}),
      ...(d.agent.maxBudgetUsd !== undefined ? { maxBudgetUsd: d.agent.maxBudgetUsd } : {}),
    },
    execution: { enabled: true, validationCommands: plan.defaultChecks, maxRepairAttempts: d.maxRepairAttempts },
    autonomy: {
      enabled: true,
      maxRunDurationMs: d.autonomy.maxRunDurationMs,
      maxTaskDurationMs: d.autonomy.maxTaskDurationMs,
      ...(d.autonomy.maxCostUsd !== undefined ? { maxCostUsd: d.autonomy.maxCostUsd } : {}),
      ...(d.autoAcceptLowRisk && lowRisk.length > 0 ? { autoAccept: { enabled: true, taskIds: lowRisk, paths: ['src', 'test', 'tests'] } } : {}),
    },
  };
  parseFactoryConfig(raw, layout.configDir); // throws with every issue if anything is off
  return raw;
}

export function renderDocuments(plan: ProductPlan, idea: IdeaInput, proposal: Proposal | undefined, generatedAt: string, docsDir = 'docs'): Record<DocumentName, string> {
  const { product, requirements, architecture, ux, dataModel, testPlan, release } = plan;
  const reqTitle = new Map([...requirements.functional.map((r) => [r.id, r.title] as const), ...requirements.nonFunctional.map((r) => [r.id, r.category] as const)]);
  const tasksFor = (pred: (t: PlanTask) => boolean) => plan.tasks.filter(pred).map((t) => t.id).join(', ') || '_none_';

  const PRODUCT = [
    header('Product', plan),
    `## Problem\n\n${product.problem}`,
    `## Target users\n\n${bullets(product.targetUsers)}`,
    `## Value proposition\n\n${product.valueProposition}`,
    `## MVP scope\n\n${bullets(product.mvpScope)}`,
    `## Out of scope (for the MVP)\n\n${bullets(product.outOfScope)}`,
    `## Differentiation\n\n${product.differentiation}`,
    `## Business model\n\n${product.businessModel}`,
    proposal ? `## Effort and costs (from the approved proposal)\n\nEstimated tasks: ${proposal.effort.estimatedTasks} (${proposal.effort.complexity}). ${proposal.effort.notes}\n\n${bullets(proposal.recurringCosts.map((c) => `${c.item}: ${c.estimate} [${LABEL[c.basis]}]${c.notes ? ` - ${c.notes}` : ''}`), '_No recurring costs identified._')}` : '',
    proposal ? `## Major risks\n\n${bullets(proposal.risks.map((r) => `**${r.severity}** ${r.risk} - mitigation: ${r.mitigation}`))}` : '',
    `## Basis of statements\n\n### User-provided\n${statementLines(plan.statements, 'user-provided')}\n\n### Verified\n${statementLines(plan.statements, 'verified')}\n\n### Assumptions (unverified)\n${statementLines(plan.statements, 'assumption')}\n\n### Recommendations (AI-generated)\n${statementLines(plan.statements, 'recommendation')}`,
  ].filter(Boolean).join('\n\n');

  const REQUIREMENTS = [
    header('Requirements', plan),
    '## Functional requirements',
    ...requirements.functional.map((r) => `### ${r.id}: ${r.title}${r.mvp ? ' (MVP)' : ' (later)'}\n\n${r.description}\n\nAcceptance criteria:\n${bullets(r.acceptanceCriteria)}\n\nImplemented by: ${tasksFor((t) => t.covers.includes(r.id))}`),
    '## Non-functional requirements',
    requirements.nonFunctional.length === 0 ? '_None._' : requirements.nonFunctional.map((r) => `- **${r.id}** (${r.category}${r.mvp ? ', MVP' : ''}): ${r.requirement} - tasks: ${tasksFor((t) => t.covers.includes(r.id))}`).join('\n'),
    '## User stories',
    requirements.userStories.length === 0 ? '_None._' : requirements.userStories.map((s) => `### ${s.id}\n\nAs ${s.asA}, I want ${s.iWant}, so that ${s.soThat}.\n\nRequirements: ${s.requirementIds.map((r) => `${r} (${reqTitle.get(r) ?? '?'})`).join(', ')}\n\nAcceptance criteria:\n${bullets(s.acceptanceCriteria)}`).join('\n\n'),
  ].join('\n\n');

  const ARCHITECTURE = [
    header('Architecture', plan),
    `Project type: **${architecture.projectType}**. Platforms: ${architecture.platforms.join(', ')}.`,
    '## Recommended stack',
    architecture.stack.map((s) => `### ${s.layer}: ${s.choice}\n\n${s.rationale}\n\n**Trade-offs:** ${s.tradeoffs}${s.alternatives.length ? `\n\n**Alternatives considered:** ${s.alternatives.join(', ')}` : ''}`).join('\n\n'),
    `## Frontend\n\n${architecture.frontend}`,
    `## Backend\n\n${architecture.backend}`,
    `## Database\n\n${architecture.database}`,
    `## Integrations\n\n${architecture.integrations.length === 0 ? '_None._' : architecture.integrations.map((i) => `- **${i.name}**: ${i.purpose}. Config: ${i.configKeys.join(', ') || 'none'}.${i.sensitive ? ' Sensitive.' : ''}${i.paid ? ' Paid service (a person must create the account).' : ''} ${i.verified ? 'API capabilities verified.' : 'API capabilities NOT verified.'}`).join('\n')}`,
    `## Authentication\n\n${architecture.authentication}`,
    `## Authorization\n\n${architecture.authorization}`,
    `## Deployment architecture\n\n${architecture.deployment}`,
    '## Validation commands\n\nThe factory runs these after every task (no shell, allowlisted executables only):\n\n' + plan.commands.map((c) => `- \`${c.name}\`: \`${[c.executable, ...c.args].join(' ')}\`${c.description ? ` - ${c.description}` : ''}${plan.defaultChecks.includes(c.name) ? ' (runs after every task)' : ''}`).join('\n'),
  ].join('\n\n');

  const UX_PLAN = [
    header('UX plan', plan),
    `## Screens\n\n${ux.screens.length === 0 ? '_No screens (no user interface)._' : ux.screens.map((s) => `- **${s.id} ${s.name}**: ${s.purpose}${s.requirementIds.length ? ` (${s.requirementIds.join(', ')})` : ''} - tasks: ${tasksFor((t) => t.screens.includes(s.id))}`).join('\n')}`,
    `## Navigation\n\n${ux.navigation}`,
    `## User journeys\n\n${ux.journeys.length === 0 ? '_None._' : ux.journeys.map((j) => `### ${j.name}\n\n${j.steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}`).join('\n\n')}`,
    `## Responsive behaviour\n\n${ux.responsive}`,
    `## Accessibility\n\n${bullets(ux.accessibility)}`,
  ].join('\n\n');

  const DATA_MODEL = [
    header('Data model', plan),
    dataModel.entities.length === 0
      ? '_No persistent entities._'
      : dataModel.entities
          .map((e) =>
            [
              `## ${e.name}`,
              e.description,
              '| Field | Type | Required | Validation |\n| --- | --- | --- | --- |\n' + e.fields.map((f) => `| ${f.name} | ${f.type} | ${f.required ? 'yes' : 'no'} | ${f.validation || '-'} |`).join('\n'),
              `Relationships:\n${bullets(e.relationships)}`,
              `Access control: ${e.accessControl}`,
              `Retention: ${e.retention}`,
              `Implemented by: ${tasksFor((t) => t.entities.includes(e.name))}`,
            ].join('\n\n'),
          )
          .join('\n\n'),
  ].join('\n\n');

  const TEST_PLAN = [
    header('Test plan', plan),
    `## Unit tests\n\n${bullets(testPlan.unit)}`,
    `## Integration tests\n\n${bullets(testPlan.integration)}`,
    `## Browser tests\n\n${bullets(testPlan.browser)}`,
    `## Security tests\n\n${bullets(testPlan.security)}`,
    `## End-to-end tests\n\n${bullets(testPlan.e2e)}`,
    `## How the factory verifies each task\n\nAfter every task the factory runs: ${plan.defaultChecks.join(', ')}. Each task also lists the checks and evidence that prove it is complete (see TASKS.json).`,
  ].join('\n\n');

  const RELEASE_PLAN = [
    header('Release plan', plan),
    '> The factory never deploys, publishes or buys services. Every step below is for a person to perform.',
    `## Hosting\n\n${release.hosting}`,
    `## Environments\n\n${bullets(release.environments)}`,
    `## Environment configuration\n\n${release.environmentVariables.length === 0 ? '_None._' : '| Variable | Purpose | Secret |\n| --- | --- | --- |\n' + release.environmentVariables.map((v) => `| ${v.name} | ${v.purpose} | ${v.secret ? 'yes - never commit; set in the host' : 'no'} |`).join('\n')}`,
    `## Domains\n\n${release.domains}`,
    `## Database migrations\n\n${release.migrations}`,
    `## Backups\n\n${release.backups}`,
    `## Monitoring\n\n${release.monitoring}`,
    `## Legal\n\n${bullets(release.legal)}`,
    `## Publication\n\n${bullets(release.publication)}`,
  ].join('\n\n');

  const RESEARCH = [
    header('Research and sources', plan),
    `Generated ${generatedAt}.`,
    `## Sources\n\n${plan.sources.length === 0 ? '_No sources. No live research was performed; external facts in these documents are assumptions._' : plan.sources.map(sourceLine).join('\n')}`,
    `## User-supplied reference URLs\n\n${bullets(idea.referenceUrls.map((u) => `${u} (provided by the user; not retrieved by the factory)`))}`,
    `## Findings\n\n${statementLines(plan.statements, 'verified')}`,
    `## Assumptions (unverified)\n\n${statementLines(plan.statements, 'assumption')}`,
    `## Unresolved questions\n\n${bullets(plan.openQuestions)}`,
    idea.clarifications.length ? `## Clarifications from the user\n\n${idea.clarifications.map((c) => `- Q: ${c.question}\n  A: ${c.answer}`).join('\n')}` : '',
  ].filter(Boolean).join('\n\n');

  return {
    'PRODUCT.md': PRODUCT + '\n',
    'REQUIREMENTS.md': REQUIREMENTS + '\n',
    'ARCHITECTURE.md': ARCHITECTURE + '\n',
    'UX_PLAN.md': UX_PLAN + '\n',
    'DATA_MODEL.md': DATA_MODEL + '\n',
    'TEST_PLAN.md': TEST_PLAN + '\n',
    'RELEASE_PLAN.md': RELEASE_PLAN + '\n',
    'RESEARCH.md': RESEARCH + '\n',
    'TASKS.json': `${JSON.stringify(tasksDocument(plan, docsDir), null, 2)}\n`,
  };
}
